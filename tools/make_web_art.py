#!/usr/bin/env python3
"""Write the themed monsters and bosses from creatures.py into web/bomb-yard.html.

The classic look draws them from these role grids (0 see-through, 1 outline, 2 main, 3 second
colour, 4 accent); the page colours them. They go between the "creatures" marker lines.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import creatures

PAGE = os.path.join(HERE, "..", "web", "bomb-yard.html")
START = "// --- creatures: generated by tools/make_web_art.py from tools/creatures.py ---"
END = "// --- end of creatures ---"

art = {}
for name in creatures.MONSTERS:
    art[name] = {"w": 16, "h": 16, "f": ["".join(str(v) for row in creatures.draw(name, 16, 16, f) for v in row) for f in (0, 1)]}
for name in creatures.BOSSES:
    art[name] = {"w": 24, "h": 16, "f": ["".join(str(v) for row in creatures.draw(name, 24, 16, f) for v in row) for f in (0, 1)]}
block = START + "\nconst CREATURE_ART = " + json.dumps(art, separators=(",", ":")) + ";\n" + END
page = open(PAGE).read()
a, b = page.index(START), page.index(END) + len(END)
open(PAGE, "w").write(page[:a] + block + page[b:])
print("wrote", len(block), "bytes of creatures")
