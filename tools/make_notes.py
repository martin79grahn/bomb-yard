#!/usr/bin/env python3
"""notes.h: NES APU timer periods for MIDI notes 33..96 (pulse and triangle)."""
CPU = 1789773
lo, hi = 33, 96
pulse = [round(CPU / (16 * 440 * 2 ** ((n - 69) / 12))) - 1 for n in range(lo, hi + 1)]
tri = [round(CPU / (32 * 440 * 2 ** ((n - 69) / 12))) - 1 for n in range(lo, hi + 1)]
with open("notes.h", "w") as f:
    f.write("/* generated by tools/make_notes.py */\n#define NOTE_LO %d\n" % lo)
    for name, t in (("PULSE", pulse), ("TRI", tri)):
        f.write("static const unsigned int %s_PERIOD[%d] = {%s};\n" % (name, len(t), ",".join(str(min(v, 2047)) for v in t)))
